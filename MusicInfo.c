void MusicInfo()
{
    LCD_DefineChar(0, c1);
    LCD_DefineChar(1, c2);
    LCD_ShowChar(1, 1, 0);
    LCD_ShowChar(1, 2, 1);
    LCD_ShowString(1, 3, ":KOTOKO");

    LCD_DefineChar(2, q1);
    LCD_DefineChar(3, q2);
    LCD_ShowChar(2, 1, 2);
    LCD_ShowChar(2, 2, 3);
    LCD_ShowString(2, 3, ":Famishin");
}

void MusicTitle()
{
    unsigned char Part, CharNum;
    for (Part = 0; Part < 4; Part++)
    {
        for (CharNum = 0; CharNum < 8; CharNum++)
        {
            LCD_DefineChar(CharNum, Title[Part][CharNum]);
            LCD_ShowChar(1 + CharNum / 4, 1 + Part * 4 + CharNum % 4, CharNum);
        }
        Delay(20);
        LCD_ShowString(1, 1 + Part * 4, "    ");
        LCD_ShowString(2, 1 + Part * 4, "    ");
    }
}