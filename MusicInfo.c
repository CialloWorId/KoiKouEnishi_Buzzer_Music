void MusicInfo_SetChar()
{
    LCD_DefineChar(1, Zuo[0]);
    LCD_DefineChar(2, Zuo[1]);
    LCD_DefineChar(3, Ci[0]);
    LCD_DefineChar(4, Ci[1]);
    LCD_DefineChar(5, Qu[0]);
    LCD_DefineChar(6, Qu[1]);
}

void MusicTitle()
{
    unsigned char Part, CharNum;
    for (Part = 0; Part < 4; Part++)
    {
        for (CharNum = 0; CharNum < 8; CharNum++)
        {
            LCD_DefineChar(CharNum, Title[Part][CharNum]);
            LCD_ShowChar(1 + CharNum / 4, 1 + Part * 4 + CharNum % 4, CharNum);
        }
        Delay(20);
        LCD_ShowString(1, 1 + Part * 4, "    ");
        LCD_ShowString(2, 1 + Part * 4, "    ");
    }
}